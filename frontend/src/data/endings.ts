// ============================================================
// 类型
// ============================================================

/** 结局文案里的一行里程碑（day 用 "Day N" 标签） */
export interface EndingMilestone {
  day: string;
  text: string;
}

/** 分享海报高光数字（k 标签 / v 数值文案） */
export interface EndingPosterHighlight {
  k: string;
  v: string;
}

/** 单个结局的完整文案包 */
export interface EndingCopy {
  /** 主标题（如「双向奔赴」） */
  title: string;
  /** 副题（如「灯塔与归船」） */
  sub: string;
  /** 一句话概述（§10 文案行） */
  desc: string;
  /** 封面 slogan（对应用户可分享的主文案） */
  slogan: {
    line: string;
    sub: string;
    desc: string;
  };
  /** 最终画像（§10：回放 Day4/5/6 决策轨迹） */
  verdict: {
    title: string;
    body: string;
  };
  /** Day1~Day7 叙事骨架（FinaleReport 用 eventLog 关键条目覆盖） */
  milestones: EndingMilestone[];
  /** per-NPC 结语模板（按 npcLibrary 依恋类型取用，{name} 为真名占位） */
  npcLineByAttachment: Record<AttachmentType, string>;
  /** 分享海报三个高光数字 */
  posterHighlights: EndingPosterHighlight[];
}

